"""Sweep the chunking strategies, compare the retrievers, write the report.

    python scripts/evaluate_retrieval.py

Two questions, answered in this order because the second depends on the first:

D9  Which chunking strategy retrieves best? Three are swept - whole section,
    paragraph, and overlapping window - and the heading-prepending flag is
    measured rather than assumed, because prepending the section heading to
    every chunk gives every chunk in a section the same words and flatters
    section-level retrieval.

D7  At the best strategy, how do BM25, dense embeddings and their fusion
    compare? Reported together with the lexical and paraphrase split, because
    an aggregate hides the thing worth knowing: a keyword index and an
    embedding fail on different questions.

Embedding the corpus takes minutes, so vectors are cached against the model
name and the exact chunk text. The first run is slow and every run after it is
not.
"""

from __future__ import annotations

import sys
from dataclasses import replace
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import pandas as pd

from src.config import Config
from src.rag.chunk import chunk_corpus
from src.rag.corpus import load_corpus
from src.rag.embed import build_dense_retriever
from src.rag.evaluate import (
    comparison_markdown,
    evaluate_retriever,
    load_questions,
)
from src.rag.retrieve import Bm25Retriever, HybridRetriever

STRATEGIES = ("section", "paragraph", "window")


def build_retrievers(chunks, config: Config):
    settings = config.rag.retrieval
    bm25 = Bm25Retriever(chunks, k1=settings.bm25_k1, b=settings.bm25_b)
    dense = build_dense_retriever(
        chunks,
        model_name=settings.embedding_model,
        batch_size=settings.batch_size,
        cache_dir=settings.cache_path,
    )
    hybrid = HybridRetriever([bm25, dense], rrf_k=settings.rrf_k)
    return {"bm25": bm25, "dense": dense, "hybrid": hybrid}


def sweep(corpus, questions, config: Config) -> tuple[pd.DataFrame, dict]:
    """Every strategy against every retriever, plus the heading flag."""
    rows: list[dict] = []
    detail: dict = {}
    settings = config.rag.retrieval

    variants = [(s, True) for s in STRATEGIES]
    # One extra run of the default strategy with headings off, to price the
    # flag rather than assume it helps.
    variants.append((config.rag.chunk.strategy, False))

    for strategy, heading in variants:
        chunk_config = replace(
            config.rag.chunk, strategy=strategy, prepend_heading=heading
        )
        chunks, report = chunk_corpus(corpus, chunk_config)
        label = f"{strategy}{'' if heading else ' (no heading)'}"
        print(f"\n{label}: {report.chunks:,} chunks, median {report.median} words")

        for name, retriever in build_retrievers(chunks, config).items():
            scores = evaluate_retriever(
                retriever, questions, k=settings.top_k, name=name
            )
            rows.append(
                {
                    "strategy": strategy,
                    "heading": heading,
                    "retriever": name,
                    "chunks": report.chunks,
                    "median_words": report.median,
                    "recall": round(scores.recall, 3),
                    "mrr": round(scores.mrr, 3),
                    "lexical": round(scores.by_kind("lexical").recall, 3),
                    "paraphrase": round(scores.by_kind("paraphrase").recall, 3),
                    "sections_per_query": round(scores.sections_per_query, 1),
                }
            )
            detail[(strategy, heading, name)] = scores
            print(
                f"    {name:<8} recall {scores.recall:.3f}  MRR {scores.mrr:.3f}"
            )

    return pd.DataFrame(rows), detail


def write_report(
    corpus,
    questions,
    table: pd.DataFrame,
    detail: dict,
    config: Config,
    path: Path,
) -> None:
    settings = config.rag.retrieval
    best = table.sort_values(["recall", "mrr"], ascending=False).iloc[0]
    winning = [
        detail[(best["strategy"], bool(best["heading"]), name)]
        for name in ("bm25", "dense", "hybrid")
    ]
    headline = max(winning, key=lambda s: (s.recall, s.mrr))

    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# 03 - Retrieval",
        "",
        "Generated by `python scripts/evaluate_retrieval.py`. Every figure is",
        "measured against the hand-written evaluation set in",
        "[`config/retrieval_questions.yaml`](../config/retrieval_questions.yaml).",
        "",
        "## Corpus",
        "",
        "```",
        corpus.summary(),
        "```",
        "",
        f"Retrieval is scored on whether the *section* that answers a question",
        f"comes back in the top {settings.top_k}, not on whether plausible text does.",
        "The official interpretation of a section counts as an answer to a",
        "question about that section; nothing else is admitted.",
        "",
        "## Chunking sweep (D9)",
        "",
        "Chunk size decides what retrieval can find, so it is swept rather than",
        "chosen. `heading` is whether the section heading was prepended to every",
        "chunk: it gives a chunk its topic, and it also gives every chunk in a",
        "section the same words, so its effect is priced rather than assumed.",
        "",
        table.to_markdown(index=False),
        "",
        f"Best: **{best['strategy']}**"
        + ("" if best["heading"] else " without headings")
        + f", {int(best['chunks']):,} chunks, median {int(best['median_words'])} words.",
        "",
        "## Retrievers (D7)",
        "",
        comparison_markdown(winning),
        "",
        "```",
        headline.summary(),
        "```",
        "",
        "## What the best retriever still misses (D8)",
        "",
        "An average hides the questions that matter. Every miss is listed with",
        "what came back instead.",
        "",
        headline.failure_markdown(),
        "",
        "## Notes",
        "",
        f"- {len(questions)} questions, "
        f"{sum(1 for q in questions if q.kind == 'lexical')} lexical and "
        f"{sum(1 for q in questions if q.kind == 'paraphrase')} paraphrased.",
        f"- Embeddings: `{settings.embedding_model}`, run locally, no API key.",
        "- Search is exact cosine similarity over the whole corpus. At five",
        "  thousand chunks an approximate index would add a dependency and lose",
        "  recall to save time that does not exist.",
        "- No stemming and no stop-word list. BM25's IDF already discounts a",
        "  word that appears everywhere; the missing stemmer is a real gap, and",
        "  part of what the dense retriever is here to cover.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    config = Config.load()
    corpus = load_corpus(config.rag.corpus_path)
    questions = load_questions(config.rag.retrieval.questions_path)
    print(f"{len(corpus)} sections, {len(questions)} questions")

    table, detail = sweep(corpus, questions, config)
    path = config.rag.retrieval.report_path
    write_report(corpus, questions, table, detail, config, path)

    print(f"\nwrote {path}\n")
    print(table.to_string(index=False))


if __name__ == "__main__":
    main()
