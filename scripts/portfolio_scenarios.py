"""Write reports/04_portfolio_scenarios.md (D16).

Runs the Layer 1 data path, scores the out-of-time holdout through the
committed champion exactly as the service would, and reports the portfolio
under three scenarios and six approval rates. Nothing is fitted here: the
champion is read from models/champion.json, and the only number solved for is
the odds multiplier that anchors the worst-vintage scenario.

    python scripts/portfolio_scenarios.py
"""

from __future__ import annotations

import sys
from pathlib import Path

# `python scripts/portfolio_scenarios.py` puts scripts/ on the import path, not
# the repository root.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from datetime import timedelta  # noqa: E402

import pandas as pd  # noqa: E402

from src.config import Config  # noqa: E402
from src.evaluation.scenarios import (  # noqa: E402
    Scenario,
    VintageAnchor,
    approval_table,
    scenario_table,
    solve_multiplier,
    worst_vintage,
)
from src.pipeline import prepare  # noqa: E402
from src.serving.artefact import load_champion  # noqa: E402
from src.serving.score import score_frame  # noqa: E402

#: The exposure column. Loan amount at origination, the only amount D2 allows.
EXPOSURE_COLUMN = "loan_amnt"


def build_scenarios(
    probability, anchor: VintageAnchor, severe_multiplier: float, cutoff
) -> tuple[Scenario, ...]:
    # The cutoff falls inside a year, so that year is only partly in the
    # training window, and the report says which part the anchor rests on.
    part = (
        f" (January to {cutoff:%B} only, the part before the cutoff)"
        if cutoff is not None and anchor.year == cutoff.year
        else ""
    )
    return (
        Scenario("base", 1.0, "champion as fitted"),
        Scenario(
            "worst_vintage",
            solve_multiplier(probability, anchor.bad_rate),
            f"mean PD set to the {anchor.year}{part} bad rate, {anchor.bad_rate:.2%} "
            f"over {anchor.loans:,} loans, the worst year of the training window",
        ),
        Scenario(
            "severe",
            severe_multiplier,
            f"odds of default x{severe_multiplier:g}, an assumption",
        ),
    )


def _money(value: float) -> str:
    return f"${value / 1e6:,.1f}m"


def write_report(
    path: Path,
    *,
    rows: int,
    observed_bad_rate: float,
    total_exposure: float,
    anchor: VintageAnchor,
    scenarios_df: pd.DataFrame,
    approvals_df: pd.DataFrame,
    scenarios: tuple[Scenario, ...],
) -> None:
    lines = [
        "# Portfolio scenarios",
        "",
        "Generated by `python scripts/portfolio_scenarios.py`. The portfolio is the",
        f"out-of-time holdout, {rows:,} resolved loans and {_money(total_exposure)} lent,",
        "scored through `models/champion.json` as the service scores it. Method and",
        "limits: D16 in `docs/DESIGN.md`.",
        "",
        "A scenario multiplies every loan's odds of default by one factor. The",
        "ranking, and so Gini, KS and every score, is the same in all of them;",
        "only the level of PD moves.",
        "",
        "## Scenarios",
        "",
        "| Scenario | Odds multiplier | Mean PD | Expected bad loans | Expected defaulted amount | vs base |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for row in scenarios_df.itertuples():
        lines.append(
            f"| {row.scenario} | {row.odds_multiplier:.3f} | {row.mean_pd:.2%} | "
            f"{row.expected_bads:,.0f} | {_money(row.expected_defaulted_amount)} | "
            f"{row.change_vs_first:+.1%} |"
        )
    lines += ["", "Where each multiplier comes from:", ""]
    lines += [f"- **{s.name}**: {s.basis}." for s in scenarios]
    tightest = approvals_df.iloc[0]
    lines += [
        "",
        f"The holdout's observed bad rate is {observed_bad_rate:.2%}, against a mean",
        f"base PD of {scenarios_df['mean_pd'].iloc[0]:.2%}: right at portfolio level.",
        "It is less right by band. In the tightest book below the champion expects",
        f"{tightest['expected_bad_rate_base']:.2%} and {tightest['observed_bad_rate']:.2%} happened,",
        "the calibration slope of the validation report seen in money. That is why",
        "a stress is read as a change from base, not as a forecast.",
        "",
        "The expected defaulted amount is PD x loan amount. It is not a loss:",
        "principal repaid before default and recoveries after it are both recorded",
        "after origination, so loss given default is out of scope and the figure is",
        "an upper bound.",
        "",
        "## Approval rates",
        "",
        "Applicants approved lowest PD first. *Observed* columns use the holdout's",
        "real outcomes; *expected* columns use the champion's PD under each",
        "scenario. No rate is recommended: a cutoff is a risk-appetite decision (D13).",
        "",
    ]
    names = [s.name for s in scenarios]
    header = (
        "| Approved | Loans | Highest PD approved | Observed bad rate | Bads declined | "
        + " | ".join(f"Expected bad rate, {n}" for n in names)
        + " |"
    )
    lines += [header, "|" + "---:|" * (5 + len(names))]
    for row in approvals_df.to_dict("records"):
        cells = [
            f"{row['approval_rate']:.0%}",
            f"{row['approved']:,}",
            f"{row['highest_pd_approved']:.2%}",
            f"{row['observed_bad_rate']:.2%}",
            f"{row['bads_declined_share']:.1%}",
        ] + [f"{row[f'expected_bad_rate_{n}']:.2%}" for n in names]
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    config = Config.load()
    data = prepare(config)
    champion = load_champion(config.serving.artefact_path)

    probability = score_frame(champion, data.test).probability_of_default
    exposure = data.test[EXPOSURE_COLUMN].to_numpy(dtype="float64")
    outcome = data.y_test.to_numpy()

    anchor = worst_vintage(
        data.train[data.date_column],
        data.y_train,
        min_loans=config.scenarios.min_vintage_loans,
    )
    scenarios = build_scenarios(
        probability,
        anchor,
        config.scenarios.severe_odds_multiplier,
        config.split.cutoff_date - timedelta(days=1)
        if config.split.cutoff_date is not None
        else None,
    )
    scenarios_df = scenario_table(probability, exposure, scenarios)
    approvals_df = approval_table(
        probability, outcome, exposure, config.scenarios.approval_rates, scenarios
    )

    write_report(
        config.scenarios.report_path,
        rows=len(probability),
        observed_bad_rate=float(outcome.mean()),
        total_exposure=float(exposure.sum()),
        anchor=anchor,
        scenarios_df=scenarios_df,
        approvals_df=approvals_df,
        scenarios=scenarios,
    )
    print(scenarios_df.drop(columns="basis").to_string(index=False))
    print(f"\nwrote {config.scenarios.report_path}")


if __name__ == "__main__":
    main()
